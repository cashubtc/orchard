/** Generate request/response contracts from the vendored CDK protos. */
import {createRequire} from 'node:module';
import {readdirSync, writeFileSync} from 'node:fs';
import path from 'node:path';
const require = createRequire(import.meta.url);
const protobuf = createRequire(require.resolve('@grpc/proto-loader'))('protobufjs');
const root = new protobuf.Root();
for (const file of readdirSync('proto/cdk').filter((name) => name.endsWith('.proto'))) root.loadSync(`proto/cdk/${file}`, {keepCase: true});
root.resolveAll();
/** Return an unambiguous exported name for a protobuf message. */
function typeName(type) {
	return type.fullName.slice(1).replaceAll('.', '_');
}
/** Match proto-loader's lossless longs and string enums. */
function fieldType(field, output) {
	if (field.resolvedType instanceof protobuf.Enum)
		return Object.keys(field.resolvedType.values)
			.map((v) => JSON.stringify(v))
			.join(' | ');
	if (field.resolvedType) return typeName(field.resolvedType) + (output ? 'Output' : '');
	if (field.type === 'string') return 'string';
	if (field.type === 'bool') return 'boolean';
	if (field.type === 'bytes') return 'Buffer';
	if (field.type.includes('64')) return output ? 'string' : 'string | number';
	return 'number';
}
let result = '// Generated by scripts/generate-cdk-rpc-types.mjs from proto/cdk. Do not edit.\n';
const methods = [];
for (const namespace of root.nestedArray) {
	for (const type of namespace.nestedArray) {
		if (type instanceof protobuf.Service) {
			for (const method of type.methodsArray)
				methods.push(
					`\t${method.name}: {request: ${typeName(method.resolvedRequestType)}; response: ${typeName(method.resolvedResponseType)}Output};`,
				);
			continue;
		}
		if (!(type instanceof protobuf.Type)) continue;
		for (const output of [false, true]) {
			result += `\nexport interface ${typeName(type)}${output ? 'Output' : ''} {\n`;
			for (const field of type.fieldsArray) {
				let value = fieldType(field, output);
				if (field.repeated) value = `(${value})[]`;
				const optional = !output || field.partOf;
				if (output && !field.repeated && field.resolvedType instanceof protobuf.Type) value += ' | null';
				result += `\t${field.name}${optional ? '?' : ''}: ${value};\n`;
			}
			result += '}\n';
		}
	}
}
result += `\nexport interface CdkRpcMethods {\n${methods.join('\n')}\n}\n`;
writeFileSync(path.resolve('src/server/modules/cashu/cdk/cdkrpc.types.ts'), result);
